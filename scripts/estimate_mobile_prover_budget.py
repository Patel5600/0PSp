#!/usr/bin/env python3
"""Mobile device memory and prover resource budget model for 0PSP spend relations.

Analytical model projecting RAM usage, trace row counts, and proving feasibility on constrained
mobile client hardware (Android LMK threshold ~384 MB, iOS Jetsam threshold ~256 MB)
across four prover architectures:
  1. Generic RISC-V zkVM (OpenVM v2.0.2 / RISC Zero) - Full monolithic relation
  2. Dense R1CS (SmallWood generic adapter) - Full relation
  3. Specialized Native Keccak AIR (Plonky3 / Binius / Stwo) - Monolithic relation
  4. 2-Tier Blinded Split-Prover - Mobile Edge Client (< 24 MB RAM) + Delegated Relayer

IMPORTANT DISCLAIMER:
  Projections generated by this module are analytical resource model estimates based on
  algorithmic complexity and hardware execution profiles, NOT empirical measurements of a
  compiled production circuit. Composed zero-knowledge witness privacy remains conditionally
  gated on implementation of verified ZK trace blinding rows (tracked in P0 Issue #36).

Parameter scaling:
  - tree_depth (d): directly controls Merkle membership hash count (2 Keccak-f permutations/level).
  - outputs (m): controls output commitment count (2 Keccak-f permutations/output).
  - Tier 1 Split-Prover is O(1) w.r.t tree_depth because Merkle path proof is delegated to Tier 2.
"""
from __future__ import annotations

import argparse
import math
from dataclasses import dataclass
from typing import Any, Dict, List, Tuple


ANDROID_LMK_RAM_LIMIT_MB = 384
IOS_JETSAM_RAM_LIMIT_MB = 256
MOBILE_TARGET_RAM_BUDGET_MB = 128
MOBILE_TARGET_TIME_BUDGET_SEC = 5.0
MOBILE_TIMEOUT_LIMIT_SEC = 60.0

# Base permutations for monolithic spend relation components:
# input_commit(2) + leaf(2) + nullifier(2) + tx_digest(2) + fixed_padding(17) = 25
# Fixed padding breakdown (17 permutations total):
#   - 4 permutations: transaction root and block context framing
#   - 4 permutations: leaf commitment tree interface framing
#   - 4 permutations: nullifier domain separation framing
#   - 5 permutations: output commitment aggregation and range-bound value balance framing
BASE_MONO_PERMUTATIONS = 25
PERMUTATIONS_PER_MERKLE_DEPTH = 2
PERMUTATIONS_PER_OUTPUT = 2

# Tier 1 Mobile Split-Prover base permutations (No Merkle path):
# input_commit(2) + nullifier(2) + tx_digest(2) + base_pad(2) = 8
BASE_TIER1_PERMUTATIONS = 8


@dataclass(frozen=True)
class ProverProfile:
    architecture: str
    target_hardware: str
    trace_rows: int
    trace_columns: int
    peak_ram_mb: float
    estimated_time_arm64_sec: float
    witness_privacy_proven: bool          # False across all profiles pending verified ZK trace blinding (Issue #36)
    witness_privacy_status: str          # e.g. "CONDITIONAL_ON_ZK_BLINDING_ROWS", "UNMASKED_WITNESS_LEAKAGE"
    witness_privacy_rationale: str
    android_mobile_status: str           # "FEASIBLE", "BORDERLINE", "FATAL_OOM"
    ios_mobile_status: str               # "FEASIBLE", "BORDERLINE", "FATAL_OOM"
    device_support_percent: float        # 0.0% to 100.0%
    rationale: str

    @property
    def witness_privacy_preserved(self) -> bool:
        """Backward-compatibility property: reflects whether witness privacy is mathematically and circuit-proven."""
        return self.witness_privacy_proven


def _next_power_of_two(n: int) -> int:
    """Return smallest power of two >= n."""
    if n <= 1:
        return 1
    return 1 << (n - 1).bit_length()


def calculate_monolithic_permutations(tree_depth: int, outputs: int) -> int:
    """Calculate total Keccak-f[1600] permutations required for a monolithic spend relation."""
    return BASE_MONO_PERMUTATIONS + (tree_depth * PERMUTATIONS_PER_MERKLE_DEPTH) + (outputs * PERMUTATIONS_PER_OUTPUT)


def calculate_tier1_permutations(outputs: int) -> int:
    """Calculate Keccak-f[1600] permutations for Tier 1 Split-Prover (independent of tree_depth)."""
    return BASE_TIER1_PERMUTATIONS + (outputs * PERMUTATIONS_PER_OUTPUT)


def evaluate_feasibility(peak_ram_mb: float, proving_time_sec: float) -> Tuple[str, str, float, str]:
    """Evaluate device feasibility and support percentage across Android and iOS constraints.

    Returns:
        (android_status, ios_status, support_percent, summary_rationale)
    """
    # Android status
    if peak_ram_mb > ANDROID_LMK_RAM_LIMIT_MB or proving_time_sec > MOBILE_TIMEOUT_LIMIT_SEC:
        android_status = "FATAL_OOM"
    elif peak_ram_mb > 192.0 or proving_time_sec > 30.0:
        android_status = "BORDERLINE"
    else:
        android_status = "FEASIBLE"

    # iOS status
    if peak_ram_mb > IOS_JETSAM_RAM_LIMIT_MB or proving_time_sec > MOBILE_TIMEOUT_LIMIT_SEC:
        ios_status = "FATAL_OOM"
    elif peak_ram_mb > MOBILE_TARGET_RAM_BUDGET_MB or proving_time_sec > 30.0:
        ios_status = "BORDERLINE"
    else:
        ios_status = "FEASIBLE"

    # Device support calculation
    if peak_ram_mb > ANDROID_LMK_RAM_LIMIT_MB or proving_time_sec > MOBILE_TIMEOUT_LIMIT_SEC:
        support_percent = 0.0
        summary = (
            f"FATAL: Infeasible on mobile. Consumes {peak_ram_mb:,.1f} MB RAM / {proving_time_sec:,.2f} s. "
            f"Exceeds OS memory caps (Android LMK: {ANDROID_LMK_RAM_LIMIT_MB} MB, iOS Jetsam: {IOS_JETSAM_RAM_LIMIT_MB} MB) "
            "or interactive timeout (60s). Terminated by OS SIGKILL."
        )
    elif peak_ram_mb > IOS_JETSAM_RAM_LIMIT_MB:
        support_percent = 45.0
        summary = (
            f"Infeasible on iOS ({peak_ram_mb:,.1f} MB exceeds {IOS_JETSAM_RAM_LIMIT_MB} MB Jetsam limit); "
            "borderline on high-end Android devices under memory pressure."
        )
    elif peak_ram_mb > 192.0 or proving_time_sec > 30.0:
        support_percent = 65.0
        summary = (
            f"Borderline on both platforms ({peak_ram_mb:,.1f} MB RAM, {proving_time_sec:,.2f} s latency). "
            "High risk of eviction under background multitasking pressure."
        )
    elif peak_ram_mb > MOBILE_TARGET_RAM_BUDGET_MB:
        support_percent = 85.0
        summary = (
            f"Feasible on Android; borderline on iOS ({peak_ram_mb:,.1f} MB exceeds target {MOBILE_TARGET_RAM_BUDGET_MB} MB budget)."
        )
    else:
        support_percent = 100.0
        summary = (
            f"Fully feasible on 100% of budget Android/iOS mobile devices "
            f"({peak_ram_mb:,.1f} MB RAM <= {MOBILE_TARGET_RAM_BUDGET_MB} MB, {proving_time_sec:,.2f} s latency)."
        )

    return android_status, ios_status, support_percent, summary


def evaluate_mobile_prover_architectures(
    *,
    tree_depth: int = 63,
    outputs: int = 1,
) -> Dict[str, Any]:
    """Calculate and compare resource requirements for 0PSP spend proving across architectures.

    Returns analytical model projections based on power-of-two STARK polynomial domain sizes
    and mobile OS memory bounds.
    """
    if tree_depth < 1 or tree_depth > 64:
        raise ValueError(f"tree_depth must be in 1..64, got {tree_depth}")
    if outputs < 1 or outputs > 1024:
        raise ValueError(f"outputs must be in 1..1024, got {outputs}")

    # Baseline 1-in/1-out depth-63 reference count: 25 + (63*2) + (1*2) = 153 permutations
    p_mono = calculate_monolithic_permutations(tree_depth, outputs)
    mono_scale = p_mono / 153.0

    p_tier1 = calculate_tier1_permutations(outputs)

    # 1. Generic zkVM (Monolithic OpenVM v2 / RISC-V Emulation)
    # Measured baseline at (d=63, m=1): 2^24 rows (16,777,216), ~1,200 cols, 2,732.0 MB RAM, 185s ARM64
    # Note on STARK power-of-two domain:
    #   At d=63: 153 permutations -> 16.78M active rows -> next power of two = 2^24 = 16,777,216 rows.
    #   At d=32: 91 permutations -> 9.98M active rows -> next power of two is STILL 2^24 = 16,777,216 rows!
    #   Therefore, domain-allocated LDE / quotient buffers (~1,950 MB) do not scale linearly with active rows.
    #   Total RAM = LDE_domain_buffer(2^k) + active_execution_buffer(active_rows).
    raw_zkvm_rows = int(p_mono * 109_655)
    zkvm_rows = _next_power_of_two(raw_zkvm_rows)
    zkvm_cols = 1_200
    base_domain_power = 24  # 2^24 baseline
    current_domain_power = int(math.log2(zkvm_rows)) if zkvm_rows > 1 else 0
    domain_expansion = 2 ** max(0, current_domain_power - base_domain_power)
    # 1,950 MB invariant domain LDE buffer at 2^24 + 782 MB active execution trace buffer
    zkvm_ram_mb = round((1_950.0 * domain_expansion) + (782.0 * mono_scale), 1)
    zkvm_time_sec = round(185.0 * mono_scale, 2)
    zkvm_android, zkvm_ios, zkvm_support, zkvm_summary = evaluate_feasibility(zkvm_ram_mb, zkvm_time_sec)

    profile_zkvm = ProverProfile(
        architecture="Monolithic Generic zkVM (OpenVM v2.0.2 / RISC-V)",
        target_hardware="Mobile ARM64 (Direct)",
        trace_rows=zkvm_rows,
        trace_columns=zkvm_cols,
        peak_ram_mb=zkvm_ram_mb,
        estimated_time_arm64_sec=zkvm_time_sec,
        witness_privacy_proven=False,
        witness_privacy_status="BLOCKED_BY_ISSUE_36",
        witness_privacy_rationale="Monolithic zkVM trace lacks verified randomized blinding rows; witness privacy unproven under evaluation queries.",
        android_mobile_status=zkvm_android,
        ios_mobile_status=zkvm_ios,
        device_support_percent=zkvm_support,
        rationale=(
            f"Consumes {zkvm_ram_mb:,.1f} MB RAM ({p_mono} Keccak permutations, domain 2^{current_domain_power}). "
            f"{zkvm_summary}"
        ),
    )

    # 2. Dense R1CS (SmallWood generic adapter)
    # Audited in CHp4.22: 307,200 constraints x 310,000 variables -> 2.082 TiB RAM at baseline.
    # Matrix size scales quadratically with constraint count O(P^2).
    smallwood_constraints = int(p_mono * 2_007.84)
    smallwood_variables = int(p_mono * 2_026.14)
    smallwood_ram_mb = round(2_183_168.0 * (mono_scale ** 2), 1)
    smallwood_android, smallwood_ios, smallwood_support, smallwood_summary = evaluate_feasibility(smallwood_ram_mb, float("inf"))

    profile_smallwood = ProverProfile(
        architecture="Dense Generic R1CS (SmallWood Python/C Adapter)",
        target_hardware="Mobile ARM64 (Direct)",
        trace_rows=smallwood_constraints,
        trace_columns=smallwood_variables,
        peak_ram_mb=smallwood_ram_mb,
        estimated_time_arm64_sec=float("inf"),
        witness_privacy_proven=False,
        witness_privacy_status="UNMASKED_WITNESS_LEAKAGE",
        witness_privacy_rationale="Dense R1CS witness vector is unblinded in reference adapter.",
        android_mobile_status=smallwood_android,
        ios_mobile_status=smallwood_ios,
        device_support_percent=smallwood_support,
        rationale=(
            f"Audited and rejected in CHp4.22. Quadratic dense expansion requires "
            f"{smallwood_ram_mb / 1024 / 1024:,.3f} TiB RAM. Completely impossible on mobile."
        ),
    )

    # 3. Specialized Native Keccak AIR (Binius / Plonky3 / Stwo with Keccak precompile)
    # Dedicated 25-lane Keccak state columns; trace width 64 cols.
    # At d=63: 153 * 856.68 = 131,072 rows = 2^17.
    # At d=32: 91 * 856.68 = 77,958 rows -> next power of two is STILL 2^17 = 131,072 rows.
    # Domain allocation (~110 MB) is invariant at 2^17; active row buffer (~70 MB) scales with active rows.
    raw_air_rows = int(p_mono * 856.68)
    air_rows = _next_power_of_two(raw_air_rows)
    air_cols = 64
    air_domain_power = int(math.log2(air_rows)) if air_rows > 1 else 0
    air_domain_expansion = 2 ** max(0, air_domain_power - 17)
    air_ram_mb = round((110.0 * air_domain_expansion) + (70.0 * mono_scale), 1)
    air_time_sec = round(9.5 * mono_scale, 2)
    air_android, air_ios, air_support, air_summary = evaluate_feasibility(air_ram_mb, air_time_sec)

    profile_air = ProverProfile(
        architecture="Specialized Native Keccak AIR (Plonky3 / Binius / Stwo)",
        target_hardware="Mobile ARM64 (Direct Monolithic)",
        trace_rows=air_rows,
        trace_columns=air_cols,
        peak_ram_mb=air_ram_mb,
        estimated_time_arm64_sec=air_time_sec,
        witness_privacy_proven=False,
        witness_privacy_status="GATED_END_TO_END_ZK",
        witness_privacy_rationale=(
            "The Python trace-blinding model has adversarial simulation tests, but no selected "
            "OpenVM/Plonky3 production prover is wired to commit randomized rows and salts into "
            "its actual trace/quotient. End-to-end witness privacy remains gated by P0 Issue #36."
        ),
        android_mobile_status=air_android,
        ios_mobile_status=air_ios,
        device_support_percent=air_support,
        rationale=(
            f"Consumes ~{air_ram_mb:,.1f} MB RAM (power-of-two domain 2^{air_domain_power}). {air_summary}"
        ),
    )

    # 4. 2-Tier Blinded Split-Prover (Mobile Client Tier 1 + Delegated Relayer Tier 2)
    # Mobile proves only secret note opening, nullifier derivation, and value balance (O(outputs), independent of tree_depth).
    # Heavy Merkle membership across tree_depth levels is proved by untrusted relayer/server.
    raw_split_rows = int(p_tier1 * 3_276.8)
    split_mobile_rows = _next_power_of_two(raw_split_rows)
    split_mobile_cols = 48
    split_mobile_ram_mb = round(18.0 + (outputs * 4.5), 1)
    split_mobile_time_sec = round(0.25 + (outputs * 0.13), 2)
    split_android, split_ios, split_support, split_summary = evaluate_feasibility(split_mobile_ram_mb, split_mobile_time_sec)

    profile_split = ProverProfile(
        architecture="2-Tier Blinded Split-Prover: Tier 1 Mobile Edge Client",
        target_hardware="Mobile ARM64 (Budget Smartphone)",
        trace_rows=split_mobile_rows,
        trace_columns=split_mobile_cols,
        peak_ram_mb=split_mobile_ram_mb,
        estimated_time_arm64_sec=split_mobile_time_sec,
        witness_privacy_proven=False,
        witness_privacy_status="GATED_END_TO_END_ZK",
        witness_privacy_rationale=(
            "Tier-1 resource figures are analytical targets. The actual Tier-1 proof circuit and "
            "end-to-end randomized trace/quotient masking are not integrated or verified; the "
            "Python blinding model is not proof of production witness privacy (P0 Issue #36 remains open)."
        ),
        android_mobile_status=split_android,
        ios_mobile_status=split_ios,
        device_support_percent=split_support,
        rationale=(
            f"Consumes {split_mobile_ram_mb:,.1f} MB RAM and executes in {split_mobile_time_sec:,.2f} s "
            f"for {outputs} output(s). Independent of tree_depth (0 Merkle node hashes on mobile). "
            f"{split_summary}"
        ),
    )

    return {
        "tree_depth": tree_depth,
        "outputs": outputs,
        "monolithic_permutations": p_mono,
        "tier1_permutations": p_tier1,
        "android_lmk_limit_mb": ANDROID_LMK_RAM_LIMIT_MB,
        "ios_jetsam_limit_mb": IOS_JETSAM_RAM_LIMIT_MB,
        "mobile_target_budget_mb": MOBILE_TARGET_RAM_BUDGET_MB,
        "profiles": [
            profile_zkvm,
            profile_smallwood,
            profile_air,
            profile_split,
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tree-depth", type=int, default=63, help="Merkle tree depth (default: 63)")
    parser.add_argument("--outputs", type=int, default=1, help="Transaction output count (default: 1)")
    args = parser.parse_args()

    results = evaluate_mobile_prover_architectures(
        tree_depth=args.tree_depth,
        outputs=args.outputs,
    )

    print("=" * 80)
    print("0PSP Mobile Prover Resource Budget & Feasibility Evaluation")
    print("=" * 80)
    print(f"Target Platform: Mobile ARM64 (Android LMK: {results['android_lmk_limit_mb']} MB, iOS Jetsam: {results['ios_jetsam_limit_mb']} MB)")
    print(f"Safe Mobile RAM Budget: <= {results['mobile_target_budget_mb']} MB")
    print(f"Parameters: Merkle Tree Depth = {results['tree_depth']} | Output Notes = {results['outputs']}")
    print(f"Permutations: Monolithic = {results['monolithic_permutations']} | Tier 1 Mobile Client = {results['tier1_permutations']}")
    print("-" * 80)

    for p in results["profiles"]:
        print(f"\n[Architecture]: {p.architecture}")
        print(f"  Target Hardware:       {p.target_hardware}")
        print(f"  Trace Dimension:       {p.trace_rows:,} rows x {p.trace_columns:,} cols")
        print(f"  Peak RAM Footprint:    {p.peak_ram_mb:,.1f} MB")
        print(f"  ARM64 Proving Time:    {p.estimated_time_arm64_sec:.2f} s")
        print(f"  Android Mobile Status: {p.android_mobile_status}")
        print(f"  iOS Mobile Status:     {p.ios_mobile_status}")
        print(f"  Device Support:        {p.device_support_percent:.1f}%")
        print(f"  Witness Privacy:       {p.witness_privacy_status} (Proven: {p.witness_privacy_proven})")
        print(f"  Assessment:            {p.rationale}")

    print("\n" + "=" * 80)
    tier1 = results["profiles"][3]
    print(f"Conclusion: 2-Tier Split-Prover isolates mobile from Merkle depth ({results['tree_depth']} levels),")
    print(f"holding client RAM at {tier1.peak_ram_mb:.1f} MB with {tier1.device_support_percent:.0f}% device support.")
    print("=" * 80)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
