"""CHp4.7 recipient-keyed nullifier candidate.

This additive V3 reference leaves all V1/V2 APIs and byte vectors unchanged.
A production relation must bind the key commitment to the same canonical
note-public-key bundle committed by the note commitment.
"""
from __future__ import annotations

import hashlib
import hmac
from dataclasses import dataclass
from typing import Final

from src.primitives.namespace import NamespaceId, ScopedCoinId
from src.primitives.nullifier import NULLIFIER_BYTES, NULLIFIER_SECRET_BYTES, NullifierSecret
from src.primitives.note_types_v3 import CoinCommitmentV3

NULLIFIER_DERIVING_KEY_V3_BYTES: Final = 48
NULLIFIER_KEY_COMMITMENT_V3_BYTES: Final = 48
NULLIFIER_V3_VERSION: Final = b"\x03"
DOMAIN_NULLIFIER_V3: Final = b"0PSP-NULLIFIER-v3-HMAC-SHA3-384"
DOMAIN_NULLIFIER_KEY_COMMITMENT_V3: Final = b"0PSP-NULLIFIER-KEY-COMMIT-v3-SHAKE256"


@dataclass(frozen=True, slots=True)
class NullifierDerivingKeyV3:
    """Recipient-controlled secret key for V3 nullifier derivation.

    It must be generated by the intended note owner, kept secret from output
    creators and observers, and delivered only through the authenticated note
    recovery/encryption path. This wrapper does not generate secure randomness.
    """

    data: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.data, bytes) or len(self.data) != NULLIFIER_DERIVING_KEY_V3_BYTES:
            raise ValueError(
                f"V3 nullifier deriving key must be exactly {NULLIFIER_DERIVING_KEY_V3_BYTES} bytes"
            )

    def __repr__(self) -> str:
        return "NullifierDerivingKeyV3(<redacted>)"


@dataclass(frozen=True, slots=True)
class NullifierV3:
    """Version-distinct canonical 48-byte V3 public nullifier."""

    value: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.value, bytes) or len(self.value) != NULLIFIER_BYTES:
            raise ValueError(f"V3 nullifier must be exactly {NULLIFIER_BYTES} bytes")

    def __repr__(self) -> str:
        return f"NullifierV3({self.value.hex()[:16]}…)"


@dataclass(frozen=True, slots=True)
class NullifierKeyCommitmentV3:
    """Fixed-width commitment to the note owner's V3 nullifier deriving key."""

    value: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.value, bytes) or len(self.value) != NULLIFIER_KEY_COMMITMENT_V3_BYTES:
            raise ValueError(
                f"V3 nullifier-key commitment must be exactly {NULLIFIER_KEY_COMMITMENT_V3_BYTES} bytes"
            )


def compute_nullifier_key_commitment_v3(
    key: NullifierDerivingKeyV3,
) -> NullifierKeyCommitmentV3:
    """Compute a domain-separated key commitment for binding inside the note's pk bundle."""
    if not isinstance(key, NullifierDerivingKeyV3):
        raise TypeError("key must be a NullifierDerivingKeyV3")
    preimage = (
        DOMAIN_NULLIFIER_KEY_COMMITMENT_V3
        + NULLIFIER_V3_VERSION
        + len(key.data).to_bytes(2, "little")
        + key.data
    )
    return NullifierKeyCommitmentV3(
        hashlib.shake_256(preimage).digest(NULLIFIER_KEY_COMMITMENT_V3_BYTES)
    )


def verify_nullifier_key_commitment_v3(
    commitment: NullifierKeyCommitmentV3,
    key: NullifierDerivingKeyV3,
) -> bool:
    """Reference equality check; a real proof must enforce the same relation in-circuit."""
    if not isinstance(commitment, NullifierKeyCommitmentV3):
        raise TypeError("commitment must be a NullifierKeyCommitmentV3")
    expected = compute_nullifier_key_commitment_v3(key)
    return hmac.compare_digest(commitment.value, expected.value)


def _validate_canonical_bundle_v3(encoded: bytes) -> bytes:
    """Validate the V3 bundle wire shape without importing the protocol module.

    The bundle parser lives in the protocol layer and imports this module for
    key-commitment types; keeping this primitive boundary cycle-free requires a
    strict local shape check. The circuit must enforce the same canonical codec.
    """
    if not isinstance(encoded, bytes):
        raise TypeError("public_key_bundle must be bytes")
    prefix = b"0PSP-NOTE-PK-BUNDLE-v3" + b"\x03"
    if not encoded.startswith(prefix):
        raise ValueError("invalid V3 note-public-key bundle domain/version")
    offset = len(prefix)

    def read_length(width: int, field: str) -> int:
        nonlocal offset
        if len(encoded) - offset < width:
            raise ValueError(f"truncated {field} length")
        value = int.from_bytes(encoded[offset:offset + width], "little")
        offset += width
        return value

    def skip(length: int, field: str) -> None:
        nonlocal offset
        if length <= 0 or len(encoded) - offset < length:
            raise ValueError(f"invalid or truncated {field}")
        offset += length

    skip(read_length(2, "auth_scheme_id"), "auth_scheme_id")
    skip(read_length(4, "auth_public_key"), "auth_public_key")
    key_commitment_length = read_length(2, "nullifier_key_commitment")
    if key_commitment_length != NULLIFIER_KEY_COMMITMENT_V3_BYTES:
        raise ValueError("nullifier_key_commitment must be exactly 48 bytes")
    if len(encoded) - offset < key_commitment_length:
        raise ValueError("invalid or truncated nullifier_key_commitment")
    key_commitment = encoded[offset:offset + key_commitment_length]
    offset += key_commitment_length
    if offset != len(encoded):
        raise ValueError("trailing bytes in V3 note-public-key bundle")
    return key_commitment


def _nullifier_v3_message(
    namespace_id: NamespaceId,
    params_id: bytes,
    public_key_bundle: bytes,
    commitment: CoinCommitmentV3,
    coin_id: ScopedCoinId,
    r_nf: NullifierSecret,
) -> tuple[bytes, bytes]:
    if not isinstance(namespace_id, NamespaceId):
        raise TypeError("namespace_id must be a NamespaceId")
    if not isinstance(params_id, bytes) or not 1 <= len(params_id) < (1 << 16):
        raise ValueError("params_id must be 1..65535 bytes")
    if not isinstance(public_key_bundle, bytes) or not public_key_bundle:
        raise ValueError("public_key_bundle must be non-empty canonical bytes")
    if len(public_key_bundle) >= (1 << 32):
        raise ValueError("public_key_bundle encoding is too large")
    if not isinstance(commitment, CoinCommitmentV3):
        raise TypeError("commitment must be a CoinCommitmentV3")
    if not isinstance(coin_id, ScopedCoinId):
        raise TypeError("coin_id must be a ScopedCoinId")
    if not isinstance(r_nf, NullifierSecret):
        raise TypeError("r_nf must be a NullifierSecret")
    key_commitment = _validate_canonical_bundle_v3(public_key_bundle)
    message = b"".join((
        DOMAIN_NULLIFIER_V3,
        NULLIFIER_V3_VERSION,
        len(params_id).to_bytes(2, "little"),
        params_id,
        len(namespace_id.data).to_bytes(2, "little"),
        namespace_id.data,
        len(public_key_bundle).to_bytes(4, "little"),
        public_key_bundle,
        len(commitment.value).to_bytes(2, "little"),
        commitment.value,
        len(coin_id.data).to_bytes(2, "little"),
        coin_id.data,
        len(r_nf.data).to_bytes(2, "little"),
        r_nf.data,
    ))
    return message, key_commitment


def compute_nullifier_v3(
    namespace_id: NamespaceId,
    params_id: bytes,
    public_key_bundle: bytes,
    commitment: CoinCommitmentV3,
    coin_id: ScopedCoinId,
    r_nf: NullifierSecret,
    nullifier_key: NullifierDerivingKeyV3,
) -> NullifierV3:
    """Compute the recipient-keyed V3 nullifier candidate.

    HMAC-SHA3-384 is used as a keyed PRF candidate. The input includes the
    exact 48-byte V3 note commitment, so changing commitment salt changes the
    keyed input and avoids V2's deterministic same-nullifier behavior for
    distinct commitments sharing the same hidden tuple. A party who knows the
    tuple, commitment, parameter ID and bundle still cannot compute the
    nullifier without the recipient-held key. A circuit must bind all fields
    to the same note witness; this helper alone proves neither property.
    """
    if not isinstance(nullifier_key, NullifierDerivingKeyV3):
        raise TypeError("nullifier_key must be a NullifierDerivingKeyV3")
    message, encoded_key_commitment = _nullifier_v3_message(
        namespace_id, params_id, public_key_bundle, commitment, coin_id, r_nf
    )
    expected_key_commitment = compute_nullifier_key_commitment_v3(nullifier_key)
    if not hmac.compare_digest(encoded_key_commitment, expected_key_commitment.value):
        raise ValueError("nullifier key does not open the commitment in public_key_bundle")
    return NullifierV3(hmac.new(nullifier_key.data, message, hashlib.sha3_384).digest())
