"""CHp4.7 recipient-keyed nullifier candidate.

This additive V3 reference leaves all V1/V2 APIs and byte vectors unchanged.
A production relation must bind the key commitment to the same canonical
note-public-key bundle committed by the note commitment.
"""
from __future__ import annotations

import hashlib
import hmac
from dataclasses import dataclass
from typing import Final

from src.primitives.namespace import NAMESPACE_ID_BYTES, NamespaceId, ScopedCoinId
from src.primitives.nullifier import NULLIFIER_BYTES, NULLIFIER_SECRET_BYTES, Nullifier, NullifierSecret

NULLIFIER_DERIVING_KEY_V3_BYTES: Final = 48
NULLIFIER_KEY_COMMITMENT_V3_BYTES: Final = 48
NULLIFIER_V3_VERSION: Final = b"\x03"
DOMAIN_NULLIFIER_V3: Final = b"0PSP-NULLIFIER-v3-HMAC-SHA3-384"
DOMAIN_NULLIFIER_KEY_COMMITMENT_V3: Final = b"0PSP-NULLIFIER-KEY-COMMIT-v3-SHAKE256"


@dataclass(frozen=True, slots=True)
class NullifierDerivingKeyV3:
    """Recipient-controlled secret key for V3 nullifier derivation.

    It must be generated by the intended note owner, kept secret from output
    creators and observers, and delivered only through the authenticated note
    recovery/encryption path. This wrapper does not generate secure randomness.
    """

    data: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.data, bytes) or len(self.data) != NULLIFIER_DERIVING_KEY_V3_BYTES:
            raise ValueError(
                f"V3 nullifier deriving key must be exactly {NULLIFIER_DERIVING_KEY_V3_BYTES} bytes"
            )

    def __repr__(self) -> str:
        return "NullifierDerivingKeyV3(<redacted>)"


@dataclass(frozen=True, slots=True)
class NullifierKeyCommitmentV3:
    """Fixed-width commitment to the note owner's V3 nullifier deriving key."""

    value: bytes

    def __post_init__(self) -> None:
        if not isinstance(self.value, bytes) or len(self.value) != NULLIFIER_KEY_COMMITMENT_V3_BYTES:
            raise ValueError(
                f"V3 nullifier-key commitment must be exactly {NULLIFIER_KEY_COMMITMENT_V3_BYTES} bytes"
            )


def compute_nullifier_key_commitment_v3(
    key: NullifierDerivingKeyV3,
) -> NullifierKeyCommitmentV3:
    """Compute a domain-separated key commitment for binding inside the note's pk bundle."""
    if not isinstance(key, NullifierDerivingKeyV3):
        raise TypeError("key must be a NullifierDerivingKeyV3")
    preimage = (
        DOMAIN_NULLIFIER_KEY_COMMITMENT_V3
        + NULLIFIER_V3_VERSION
        + len(key.data).to_bytes(2, "little")
        + key.data
    )
    return NullifierKeyCommitmentV3(
        hashlib.shake_256(preimage).digest(NULLIFIER_KEY_COMMITMENT_V3_BYTES)
    )


def verify_nullifier_key_commitment_v3(
    commitment: NullifierKeyCommitmentV3,
    key: NullifierDerivingKeyV3,
) -> bool:
    """Reference equality check; a real proof must enforce the same relation in-circuit."""
    if not isinstance(commitment, NullifierKeyCommitmentV3):
        raise TypeError("commitment must be a NullifierKeyCommitmentV3")
    expected = compute_nullifier_key_commitment_v3(key)
    return hmac.compare_digest(commitment.value, expected.value)


def _nullifier_v3_message(
    namespace_id: NamespaceId,
    public_key_bundle: bytes,
    coin_id: ScopedCoinId,
    r_nf: NullifierSecret,
) -> bytes:
    if not isinstance(namespace_id, NamespaceId):
        raise TypeError("namespace_id must be a NamespaceId")
    if not isinstance(public_key_bundle, bytes) or not public_key_bundle:
        raise ValueError("public_key_bundle must be non-empty canonical bytes")
    if len(public_key_bundle) >= (1 << 32):
        raise ValueError("public_key_bundle encoding is too large")
    if not isinstance(coin_id, ScopedCoinId):
        raise TypeError("coin_id must be a ScopedCoinId")
    if not isinstance(r_nf, NullifierSecret):
        raise TypeError("r_nf must be a NullifierSecret")
    return b"".join((
        DOMAIN_NULLIFIER_V3,
        NULLIFIER_V3_VERSION,
        len(namespace_id.data).to_bytes(2, "little"),
        namespace_id.data,
        len(public_key_bundle).to_bytes(4, "little"),
        public_key_bundle,
        len(coin_id.data).to_bytes(2, "little"),
        coin_id.data,
        len(r_nf.data).to_bytes(2, "little"),
        r_nf.data,
    ))


def compute_nullifier_v3(
    namespace_id: NamespaceId,
    public_key_bundle: bytes,
    coin_id: ScopedCoinId,
    r_nf: NullifierSecret,
    nullifier_key: NullifierDerivingKeyV3,
) -> Nullifier:
    """Compute the recipient-keyed V3 nullifier candidate.

    HMAC-SHA3-384 is used as a keyed PRF candidate. Unlike V2, a party who
    knows the output tuple and public-key bundle still cannot compute the
    nullifier without the recipient-held key. The proof relation must also
    enforce that the key opens the key commitment embedded in this exact
    public_key_bundle. This reference helper alone proves neither property.
    """
    if not isinstance(nullifier_key, NullifierDerivingKeyV3):
        raise TypeError("nullifier_key must be a NullifierDerivingKeyV3")
    message = _nullifier_v3_message(
        namespace_id, public_key_bundle, coin_id, r_nf
    )
    return Nullifier(hmac.new(nullifier_key.data, message, hashlib.sha3_384).digest())
